                <h2>2. Estatal y municipal</h2>
                <p>No hay una licencia federal para una estética canina. Cada ayuntamiento define, en su reglamento de unidades económicas, si necesitas <strong>licencia o aviso de funcionamiento</strong>, <strong>uso de suelo</strong>, <strong>programa interno de protección civil</strong> y permiso de anuncio.</p>
                <p>En la Ciudad de México, la <a href="https://paot.org.mx/centro/leyes-normas-htmls/ley-de-protecci-n-489.html" target="_blank" rel="noopener">Ley de Protección y Bienestar de los Animales</a> incluye expresamente la estética y el spa entre los servicios de atención animal. Verifica la ley de tu estado: no todas son iguales.</p>

