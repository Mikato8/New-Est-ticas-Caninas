                <h2>4. Higiene y bienestar: lo técnico</h2>
                <ul>
                    <li><strong>Baño:</strong> agua tibia, productos para mascotas y enjuague hasta que salga claro. La dilución depende de la ficha del fabricante; no hay una proporción universal.</li>
                    <li><strong>Secado:</strong> temperatura tibia, boquilla en movimiento y supervisión continua. Nunca dejes a un perro solo en jaula de secado.</li>
                    <li><strong>Uñas:</strong> cortes de 1 a 2 mm; detente antes del vaso. Ten polvo hemostático a mano.</li>
                    <li><strong>Oídos:</strong> limpia solo el pabellón. Nada de cotonetes en el canal ni alcohol o agua oxigenada.</li>
                    <li><strong>Glándulas anales:</strong> no se vacían de rutina. Solo con signos o indicación veterinaria.</li>
                    <li><strong>Doble capa:</strong> no rasurar. El manto aísla del calor y protege del sol.</li>
                    <li><strong>Manejo:</strong> señales de miedo, bozal de cesta si hace falta y derivación cuando no se puede trabajar seguro.</li>
                    <li><strong>Equipo:</strong> limpia y desinfecta tijeras, máquinas, mesas y tinas entre perros, con tiempo de contacto.</li>
                </ul>

                <h2>5. Mitos y prácticas de riesgo</h2>
                <table>
                    <thead><tr><th>Práctica</th><th>Por qué evitarla</th></tr></thead>
                    <tbody>
                        <tr><td>Rasurar un manto doble “para el calor”</td><td>Puede causar alopecia, quemaduras y alterar la termorregulación. La ASPCA lo desaconseja expresamente.</td></tr>
                        <tr><td>“Anestesia para estética”</td><td>Es un acto veterinario con riesgo anestésico. Un estilista no debe sedar ni anestesiar.</td></tr>
                        <tr><td>Lazo al cuello para sujetar</td><td>Riesgo de asfixia y lesión cervical. Usa arnés y sujeción de dos puntos.</td></tr>
                        <tr><td>Vaciado de glándulas anales de rutina</td><td>Puede traumatizar e infectar. Solo con signos o indicación veterinaria.</td></tr>
                        <tr><td>Talco o perfume en aerosol cerca de la cara</td><td>Irrita vías respiratorias y ojos. Aplica con cuidado y ventila.</td></tr>
                        <tr><td>Hisopo dentro del oído</td><td>Empuja la suciedad y puede lesionar el tímpano.</td></tr>
                    </tbody>
                </table>

